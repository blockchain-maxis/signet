#!/usr/bin/env node
// Regenerates packages/types/generated/wallet_source.go from the canonical
// WALLET_SOURCES list in packages/types/src/wallet-source.ts, so the Go CLI
// can consume the same allowed values without hand-copying them.
//
// Run this after changing wallet-source.ts. CI (scripts/check-wallet-source-go.mjs)
// fails the build if the checked-in .go file drifts from what this would produce.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const tsPath = resolve(root, 'packages/types/src/wallet-source.ts');
const goPath = resolve(root, 'packages/types/generated/wallet_source.go');

export function parseWalletSources(source, file) {
  const match = source.match(/WALLET_SOURCES\s*=\s*\[([^\]]*)\]\s*as const/);
  if (!match) {
    console.error(`${file}: could not find \`WALLET_SOURCES = [...] as const\``);
    process.exit(1);
  }
  const values = [...match[1].matchAll(/'([^']*)'/g)].map((m) => m[1]);
  if (values.length === 0) {
    console.error(`${file}: found WALLET_SOURCES but parsed zero values`);
    process.exit(1);
  }
  return values;
}

export function renderGo(values) {
  // gofmt aligns the columns of a const block, so pad the identifiers here —
  // otherwise `gofmt -l` flags this file the moment the Go CLI's lint job runs
  // over it, and the fix would have to be hand-edited into generated output.
  const width = Math.max(...values.map((v) => goIdent(v).length));
  const constLines = values
    .map((v) => `\t${goIdent(v).padEnd(width)} WalletSource = "${v}"`)
    .join('\n');
  const sliceLines = values.map((v) => `\t${goIdent(v)},`).join('\n');

  return `// Code generated by scripts/generate-wallet-source-go.mjs from
// packages/types/src/wallet-source.ts. DO NOT EDIT by hand — change the
// TypeScript source of truth and regenerate instead.

package signettypes

// WalletSource is the provenance of a Wallet binding, mirroring the
// TypeScript WalletSource union in packages/types/src/wallet-source.ts.
type WalletSource string

const (
${constLines}
)

// WalletSources lists every allowed WalletSource value.
var WalletSources = []WalletSource{
${sliceLines}
}

// IsWalletSource reports whether value is one of the allowed WalletSource values.
func IsWalletSource(value string) bool {
\tfor _, s := range WalletSources {
\t\tif string(s) == value {
\t\t\treturn true
\t\t}
\t}
\treturn false
}
`;
}

function goIdent(value) {
  return `WalletSource${value.charAt(0).toUpperCase()}${value.slice(1)}`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const tsSource = await readFile(tsPath, 'utf8');
  const values = parseWalletSources(tsSource, tsPath);
  await writeFile(goPath, renderGo(values));
  console.log(`Wrote ${goPath.slice(root.length + 1)} from ${values.length} value(s).`);
}
