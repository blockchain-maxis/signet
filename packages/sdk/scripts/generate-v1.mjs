#!/usr/bin/env node
// Generates src/generated/v1.ts, the v1 API's types, from the committed
// OpenAPI snapshot docs/api/openapi-v1.json (#654), so the SDK and the API
// cannot drift.
//
//   node scripts/generate-v1.mjs           # write it
//   node scripts/generate-v1.mjs --check   # fail when it is stale (CI)
//
// SpecJson embeds its own `definitions` (it is the spec JSON Schema, $ref'd
// into the document), which openapi-typescript cannot type through. They are
// hoisted to components.schemas as SpecJson_<name> first; the API document
// itself is unchanged.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = new URL('../../../', import.meta.url);
const snapshot = new URL('docs/api/openapi-v1.json', root);
const out = new URL('../src/generated/v1.ts', import.meta.url);

const doc = JSON.parse(readFileSync(snapshot, 'utf8'));
const schemas = doc.components.schemas;
for (const [name, schema] of Object.entries(schemas)) {
  if (!schema.definitions) continue;
  const prefix = `#/components/schemas/${name}/definitions/`;
  const rewrite = (node) => {
    if (Array.isArray(node)) return node.map(rewrite);
    if (!node || typeof node !== 'object') return node;
    return Object.fromEntries(
      Object.entries(node).map(([k, v]) =>
        k === '$ref' && typeof v === 'string' && v.startsWith(prefix)
          ? [k, `#/components/schemas/${name}_${v.slice(prefix.length)}`]
          : [k, rewrite(v)],
      ),
    );
  };
  const { definitions, ...rest } = schema;
  for (const [def, body] of Object.entries(definitions)) schemas[`${name}_${def}`] = rewrite(body);
  schemas[name] = rewrite(rest);
}

const header = `/**
 * Generated by packages/sdk/scripts/generate-v1.mjs from docs/api/openapi-v1.json.
 * Do not edit: change apps/web/lib/api/v1/openapi.ts, export the snapshot, and
 * run \`pnpm --filter @signet/sdk generate\`.
 */

`;
const text = header + astToString(await openapiTS(doc));

if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== text) {
    console.error(`${fileURLToPath(out)} is stale; run \`pnpm --filter @signet/sdk generate\`.`);
    process.exit(1);
  }
  console.log('src/generated/v1.ts is current.');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${fileURLToPath(out)}`);
}
