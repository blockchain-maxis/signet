import { test } from 'node:test';
import assert from 'node:assert/strict';
import { renderStandaloneSvg } from './render.ts';
import { VIZ_TOKENS } from './tokens.ts';
import type { PositionedDiagramModel } from './layout.ts';

const model: PositionedDiagramModel = {
  layoutVersion: 1,
  width: 320,
  height: 120,
  groups: [],
  edges: [],
  nodes: [
    {
      id: 'fn:test',
      name: 'test',
      label: 'test',
      kind: 'function',
      column: 0,
      truncated: false,
      x: 24,
      y: 24,
      width: 100,
      height: 30,
    },
  ],
};
const provenance = { address: 'C'.repeat(56), network: 'testnet', wasmHash: 'a'.repeat(64) };
for (const theme of ['dark', 'light', 'auto'] as const) {
  test(`standalone ${theme}: one self-contained style, canvas and complete provenance`, () => {
    const svg = renderStandaloneSvg(model, { theme, provenance });
    assert.equal(svg.match(/<style>/g)?.length, 1);
    assert.match(svg, /viewBox="0 0 [0-9]+ 236"/);
    assert.ok(svg.includes(VIZ_TOKENS[theme === 'auto' ? 'light' : theme].ground));
    for (const value of Object.values(provenance)) assert.ok(svg.includes(value));
    assert.ok(svg.includes('Generated by Signet from the deployed contract interface'));
    assert.equal(svg.includes('prefers-color-scheme'), theme === 'auto');
    assert.doesNotMatch(svg, /var\(|<script|<image|href=|style=/);
    assert.equal(svg, renderStandaloneSvg(model, { theme, provenance }));
  });
}
test('untrusted labels and provenance cannot create SVG elements or attributes', () => {
  const malicious = '</text><script>alert("x")</script>&';
  const svg = renderStandaloneSvg(
    { ...model, nodes: model.nodes.map((n) => ({ ...n, name: malicious, label: malicious })) },
    {
      theme: 'light',
      provenance: { ...provenance, address: malicious },
    },
  );
  assert.doesNotMatch(svg, /<script>/);
  assert.ok(svg.includes('&lt;script&gt;'));
  assert.ok(svg.includes('&quot;x&quot;'));
  assert.ok(svg.includes('&amp;'));
});

test('invalid XML characters are replaced without dropping valid Unicode', () => {
  const svg = renderStandaloneSvg(model, {
    theme: 'light',
    provenance: { ...provenance, address: 'a' + String.fromCharCode(0, 0xd800) + '??' },
  });
  assert.ok(svg.includes('a\uFFFD\uFFFD??'));
});
