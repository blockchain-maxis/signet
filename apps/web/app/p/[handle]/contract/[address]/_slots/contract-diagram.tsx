import Link from 'next/link';
import type { SpecJson } from '@signet/spec';
import { diagramNamesFromSpec, parseDiagramState } from '@/lib/diagram-state';
import { renderContractDiagram } from '@/lib/server/contract-diagram';
import { SectionLabel } from '../../../_components/section-label';
import { DiagramEnhancer } from './diagram-enhancer';
import { SlotPlaceholder } from './slot-placeholder';
import type { ContractSlotProps } from './slot-props';

const MONO = { fontFamily: 'var(--font-mono)' } as const;
const DISPLAY = { fontFamily: 'var(--font-display)' } as const;

/** The page's `searchParams`, after Next has awaited it. */
export type DiagramQuery = Readonly<Record<string, string | readonly string[] | undefined>>;

export interface ContractDiagramProps extends ContractSlotProps {
  query?: DiagramQuery;
}

/**
 * Diagram slot (#450, #498, #502).
 *
 * The diagram is server-rendered from the URL's state, so a collapsed group is
 * a real link to the state that expands it and the whole feature works with
 * JavaScript off. `DiagramEnhancer` only swaps the server fragment in place.
 *
 * When the interface could not be read, the §2.4 fallback says why and links
 * to Functions; a render failure says the picture is unavailable rather than
 * drawing an empty frame.
 */
export function ContractDiagram({
  handle,
  address,
  network,
  wasmHash,
  spec,
  query = {},
}: ContractDiagramProps) {
  if (spec.kind === 'failure') {
    return <SlotPlaceholder slot="diagram" props={{ handle, address, network, wasmHash, spec }} />;
  }

  const contractBase = `/p/${encodeURIComponent(handle)}/contract/${encodeURIComponent(address)}`;
  const diagramPath = `${contractBase}/diagram`;
  // The loader's spec is a full `SpecJson`; `SpecInput` types only the slice
  // the Overview reads.
  const specJson = spec.spec as SpecJson;
  const names = diagramNamesFromSpec(specJson);
  const state = parseDiagramState(query, names);
  const rendered = renderContractDiagram({
    spec: specJson,
    names,
    state,
    contractBase,
    diagramPath,
    wasmHash: specJson.wasmHash ?? null,
    title: `${address} contract interface`,
  });

  return (
    <section data-testid="slot-diagram">
      <SectionLabel as="h2">Diagram</SectionLabel>
      {rendered.ok ? (
        <div id="contract-diagram" data-diagram-root data-fragment-base={`${diagramPath}/fragment`}>
          <p className="sr-only" data-diagram-status aria-live="polite" />
          {/*
            The SVG is generated by `renderDiagramSvg`, which escapes every
            spec-derived label and attribute. No user input reaches this
            string, so inlining it is the server-first render, not raw HTML.
          */}
          <div
            className="diagram-container mt-6"
            dangerouslySetInnerHTML={{ __html: rendered.svg }}
          />
          <DiagramEnhancer rootId="contract-diagram" />
        </div>
      ) : (
        <div className="mt-6 max-w-[65ch]">
          <p
            className="mb-3 text-[20px] font-bold tracking-[-0.015em] text-[#f5f4ee]"
            style={DISPLAY}
          >
            The diagram could not be drawn
          </p>
          <p className="text-[13px] leading-[1.7] text-[#b8b5a8]" style={MONO}>
            The interface is readable, but its diagram could not be built. The Functions tab lists
            everything the interface contains.
          </p>
          <Link
            href={`${contractBase}/functions`}
            className="mt-4 inline-block text-[10px] uppercase tracking-[0.2em] text-[#e05a4b] transition-colors hover:text-[#f0806f] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[#e05a4b] focus-visible:ring-offset-2 focus-visible:ring-offset-[#0a0908]"
            style={MONO}
          >
            Open Functions
          </Link>
        </div>
      )}
    </section>
  );
}
